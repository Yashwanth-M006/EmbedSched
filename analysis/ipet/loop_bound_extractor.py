"""
analysis/ipet/loop_bound_extractor.py — Loop Bound Extraction for IPET WCET Analysis

Implements Phase 3 of the IPET pipeline:
  Determines the maximum iteration count for each detected loop header
  according to strict source priority:
    1. User Annotations (from schedule.json / CLI / dict)
    2. GCC -fopt-info-loop (proven SCEV compiler bounds bridged via DWARF lines)
    3. DWARF Debug Info (.debug_info / DW_TAG_loop / DW_TAG_variable / DW_TAG_subrange_type)
    4. Static Constant Pattern Detection (CMP reg, #N before conditional back-edge)
    5. Conservative Fallback (--max-loop-bound, default 1000) -> [IPET-CONSERVATIVE]
"""

from dataclasses import dataclass, field
import glob
import os
import re
from typing import Dict, List, Optional, Set, Tuple, Union

from elftools.elf.elffile import ELFFile

from .cfg_builder import BasicBlock, FunctionCFG, Instruction, is_conditional_branch


@dataclass
class LoopBoundResult:
    """Container for resolved loop bounds and provenance information."""
    bounds: Dict[str, int] = field(default_factory=dict)
    sources: Dict[str, str] = field(default_factory=dict)
    unbounded_loops: List[str] = field(default_factory=list)
    is_conservative: bool = False
    fallback_inflation_warning: bool = False
    wcet_tag: str = "[IPET]"

    def get_bound(self, bb_id: str) -> Optional[int]:
        return self.bounds.get(bb_id)


@dataclass
class OptInfoLoopRecord:
    """Represents a single loop analysis note from GCC -fopt-info-loop."""
    filename: str
    line: int
    column: Optional[int]
    bound: int
    raw_message: str


# ─────────────────────────────────────────────────────────────────────────────
# 1. User Annotations Normalization
# ─────────────────────────────────────────────────────────────────────────────

def normalize_user_loop_bounds(
    user_bounds: Optional[Dict[Union[str, int], int]],
    cfg: Optional[FunctionCFG] = None,
) -> Dict[str, int]:
    """
    Normalizes user-specified loop bounds into a canonical mapping:
      bb_id (e.g. 'BB_08000200') -> max_iterations (int)

    Accepts keys as:
      - Canonical BB IDs: 'BB_08000200'
      - Loop IDs: 'LOOP_08000200'
      - Hex addresses as string: '0x08000200' or '0x8000200'
      - Integer addresses: 0x08000200
      - Function name (if function contains only 1 loop): 'system_init'
    """
    if not user_bounds:
        return {}

    normalized: Dict[str, int] = {}

    addr_to_bid: Dict[int, str] = {}
    loop_headers: List[str] = []
    if cfg:
        for bid, bb in cfg.blocks.items():
            addr_to_bid[bb.address] = bid
            if bb.is_loop_header:
                loop_headers.append(bid)

    for key, val in user_bounds.items():
        try:
            bound_int = int(val)
        except (ValueError, TypeError):
            continue

        if bound_int < 0:
            continue

        # Case 1: Canonical BB ID
        if isinstance(key, str) and key.startswith("BB_"):
            normalized[key] = bound_int

        # Case 2: Loop ID (e.g. LOOP_08000200)
        elif isinstance(key, str) and key.startswith("LOOP_"):
            bb_candidate = "BB_" + key[5:]
            normalized[bb_candidate] = bound_int

        # Case 3: Hex address string
        elif isinstance(key, str) and (key.startswith("0x") or key.startswith("0X")):
            try:
                addr = int(key, 16)
                if addr in addr_to_bid:
                    normalized[addr_to_bid[addr]] = bound_int
                else:
                    normalized[f"BB_{addr:08x}"] = bound_int
            except ValueError:
                pass

        # Case 4: Integer address
        elif isinstance(key, int):
            if key in addr_to_bid:
                normalized[addr_to_bid[key]] = bound_int
            else:
                normalized[f"BB_{key:08x}"] = bound_int

        # Case 5: Function name (applies if function has exactly 1 loop)
        elif isinstance(key, str) and cfg and key == cfg.name:
            if len(loop_headers) == 1:
                normalized[loop_headers[0]] = bound_int

    return normalized


# ─────────────────────────────────────────────────────────────────────────────
# 2. GCC -fopt-info-loop Parser & DWARF Line Table Correlator
# ─────────────────────────────────────────────────────────────────────────────

OPT_INFO_PATTERN = re.compile(
    r'(?P<file>[^:\s]+):(?P<line>\d+)(?::(?P<col>\d+))?:\s*'
    r'(?:note|optimized|info)?:\s*'
    r'.*?(?:iterates\s+(?:at\s+most\s+|0\.\.)?|upper\s+bound:?\s*|bound\s*=\s*)(?P<bound>\d+)\s*(?:times)?',
    re.IGNORECASE
)


def parse_gcc_opt_info(opt_info_source: Union[str, List[str]]) -> List[OptInfoLoopRecord]:
    """
    Parses compiler output generated by GCC's `-fopt-info-loop` or `-fopt-info-loop-all`.
    Accepts either a filepath or a list of output lines.
    """
    records: List[OptInfoLoopRecord] = []

    lines: List[str] = []
    if isinstance(opt_info_source, str):
        if os.path.exists(opt_info_source):
            with open(opt_info_source, 'r', encoding='utf-8', errors='ignore') as f:
                lines = f.readlines()
        else:
            lines = opt_info_source.splitlines()
    else:
        lines = opt_info_source

    for line in lines:
        line_clean = line.strip()
        if not line_clean:
            continue
        m = OPT_INFO_PATTERN.search(line_clean)
        if m:
            try:
                fpath = m.group("file").replace("\\", "/")
                lineno = int(m.group("line"))
                col = int(m.group("col")) if m.group("col") else None
                bound = int(m.group("bound"))
                records.append(
                    OptInfoLoopRecord(
                        filename=fpath,
                        line=lineno,
                        column=col,
                        bound=bound,
                        raw_message=line_clean,
                    )
                )
            except (ValueError, TypeError):
                continue

    return records


def extract_dwarf_line_map(elf_path: str) -> Dict[Tuple[str, int], List[int]]:
    """
    Extracts source-line-to-address mapping from the ELF's DWARF `.debug_line` table.
    Returns:
        Mapping: (base_filename, line_number) -> List[machine_address]
    """
    line_map: Dict[Tuple[str, int], List[int]] = {}

    if not os.path.exists(elf_path):
        return line_map

    try:
        with open(elf_path, 'rb') as f:
            elf = ELFFile(f)
            if not elf.has_dwarf_info():
                return line_map

            dwarf = elf.get_dwarf_info()
            for cu in dwarf.iter_CUs():
                lp = dwarf.line_program_for_CU(cu)
                if not lp:
                    continue

                files = [fe.name.decode('utf-8', errors='ignore') for fe in lp['file_entry']]
                for entry in lp.get_entries():
                    state = entry.state
                    if state and not state.end_sequence and state.file <= len(files):
                        fname = files[state.file - 1]
                        base_fname = os.path.basename(fname)
                        key = (base_fname, state.line)
                        line_map.setdefault(key, []).append(state.address)
    except Exception:
        pass

    return line_map


def correlate_opt_info_to_cfg(
    records: List[OptInfoLoopRecord],
    elf_path: str,
    cfg: FunctionCFG,
) -> Dict[str, Tuple[int, str]]:
    """
    Correlates GCC -fopt-info-loop records with CFG loop header basic blocks
    using DWARF line numbers.

    Returns:
        Mapping: header_bb_id -> (bound, provenance_info)
    """
    bounds: Dict[str, Tuple[int, str]] = {}
    if not records or not os.path.exists(elf_path):
        return bounds

    loop_headers = [bid for bid, bb in cfg.blocks.items() if bb.is_loop_header]
    if not loop_headers:
        return bounds

    line_map = extract_dwarf_line_map(elf_path)
    if not line_map:
        return bounds

    # Map address to basic block
    addr_to_bid: Dict[int, str] = {}
    for bid, bb in cfg.blocks.items():
        for insn in bb.instructions:
            addr_to_bid[insn.address] = bid

    # Build loop membership: header -> all blocks in its natural loop
    loop_members: Dict[str, Set[str]] = {}
    for src_id, dst_id in cfg.back_edges:
        members = {dst_id, src_id}
        # Backward search from latch (src_id) up to header (dst_id)
        queue = [src_id]
        visited = {src_id, dst_id}
        while queue:
            curr = queue.pop(0)
            for pred in cfg.blocks[curr].predecessors:
                if pred not in visited and pred in cfg.blocks:
                    visited.add(pred)
                    members.add(pred)
                    queue.append(pred)
        loop_members.setdefault(dst_id, set()).update(members)

    for rec in records:
        base_name = os.path.basename(rec.filename)

        # Collect candidate addresses within a +/- 2 line tolerance window
        candidate_addrs: List[int] = []
        for line_offset in (0, 1, -1, 2, -2):
            key = (base_name, rec.line + line_offset)
            if key in line_map:
                candidate_addrs.extend(line_map[key])

        # Find which loop header this record corresponds to
        target_header: Optional[str] = None

        # Direct hit on a loop header
        for addr in candidate_addrs:
            bid = addr_to_bid.get(addr)
            if bid and bid in loop_headers:
                target_header = bid
                break

        # Hit on any block belonging to a loop
        if not target_header:
            for addr in candidate_addrs:
                bid = addr_to_bid.get(addr)
                if bid:
                    for hdr_id, members in loop_members.items():
                        if bid in members:
                            target_header = hdr_id
                            break
                    if target_header:
                        break

        # Fallback for single loop function
        if not target_header and len(loop_headers) == 1:
            # Verify at least one candidate address is within function address range
            first_bb = cfg.blocks[cfg.entry_bb]
            fn_start = first_bb.address
            last_bb = list(cfg.blocks.values())[-1]
            fn_end = last_bb.end_address
            if any(fn_start <= a <= fn_end for a in candidate_addrs):
                target_header = loop_headers[0]

        if target_header and 1 <= rec.bound <= 100000:
            prov = f"gcc_opt_info({rec.filename}:{rec.line} -> {target_header})"
            bounds[target_header] = (rec.bound, prov)
            cfg.blocks[target_header].loop_bound = rec.bound

    return bounds


# ─────────────────────────────────────────────────────────────────────────────
# 3. Static Constant-Bound Pattern Detection
# ─────────────────────────────────────────────────────────────────────────────

def _parse_immediate(op_str: str) -> Optional[int]:
    """Parses immediate value from an ARM operand string, e.g. '#0x3e8' or '#100'."""
    m = re.search(r'#(?:\s*0x([0-9a-fA-F]+)|\s*([0-9]+))', op_str)
    if m:
        try:
            return int(m.group(1), 16) if m.group(1) else int(m.group(2), 10)
        except ValueError:
            pass
    return None


def detect_constant_loop_bound(cfg: FunctionCFG) -> Dict[str, int]:
    """
    Scans loop structures in the CFG to identify static constant loop bounds.
    Looks for comparison instructions (e.g. CMP reg, #N) governing loop termination.

    Recognizes:
      1. Condition in Loop Header (while/for jump-to-test loops):
         `BB_header`:
            ldr/mov r3, ...
            cmp.w r3, #N
            blo/bne/blt body_bb
      2. Condition in Loop Latch (do-while / post-tested loops):
         `BB_latch`:
            adds r3, #1
            cmp r3, #N
            bne/blo header_bb
      3. Countdown loops:
         `subs r3, #1; bne header_bb` with pre-loop initialization `mov r3, #N`

    Returns:
      Mapping: header_bb_id -> bound (1 <= bound <= 100,000)
    """
    bounds: Dict[str, int] = {}

    for src_id, dst_id in cfg.back_edges:
        if dst_id not in cfg.blocks:
            continue
        header_bb = cfg.blocks[dst_id]
        latch_bb = cfg.blocks.get(src_id)

        detected_bound: Optional[int] = None

        # ── Strategy A: Check instructions inside the loop header block ──────
        if header_bb.instructions:
            insns = header_bb.instructions
            for idx, ins in enumerate(insns):
                m = ins.mnemonic.lower()
                if is_conditional_branch(m):
                    for back_i in range(idx - 1, max(-1, idx - 4), -1):
                        prev = insns[back_i]
                        prev_m = prev.mnemonic.lower()
                        if prev_m.startswith("cmp") or prev_m.startswith("cmn"):
                            imm = _parse_immediate(prev.op_str)
                            if imm is not None and 1 <= imm <= 100000:
                                if m in ('ble', 'ble.w', 'bls', 'bls.w'):
                                    detected_bound = imm + 1
                                else:
                                    detected_bound = imm
                                break
                    if detected_bound is not None:
                        break

        # ── Strategy B: Check instructions inside latch block (back-edge source)
        if detected_bound is None and latch_bb and latch_bb.instructions:
            insns = latch_bb.instructions
            last_idx = len(insns) - 1
            last_ins = insns[last_idx]
            if is_conditional_branch(last_ins.mnemonic):
                for back_i in range(last_idx - 1, max(-1, last_idx - 4), -1):
                    prev = insns[back_i]
                    prev_m = prev.mnemonic.lower()
                    if prev_m.startswith("cmp") or prev_m.startswith("cmn"):
                        imm = _parse_immediate(prev.op_str)
                        if imm is not None and 1 <= imm <= 100000:
                            if last_ins.mnemonic.lower() in ('ble', 'ble.w', 'bls', 'bls.w'):
                                detected_bound = imm + 1
                            else:
                                detected_bound = imm
                            break
                    elif prev_m in ('subs', 'sub') and '#1' in prev.op_str.replace(" ", ""):
                        # Decrementing loop: check initialization in predecessors of header
                        for pred_id in header_bb.predecessors:
                            if pred_id == src_id or pred_id not in cfg.blocks:
                                continue
                            pred_bb = cfg.blocks[pred_id]
                            for pred_ins in reversed(pred_bb.instructions[-4:]):
                                if pred_ins.mnemonic.lower().startswith("mov"):
                                    init_imm = _parse_immediate(pred_ins.op_str)
                                    if init_imm is not None and 1 <= init_imm <= 100000:
                                        detected_bound = init_imm
                                        break
                            if detected_bound is not None:
                                break

        if detected_bound is not None and 1 <= detected_bound <= 100000:
            bounds[dst_id] = detected_bound
            header_bb.loop_bound = detected_bound

    return bounds


# ─────────────────────────────────────────────────────────────────────────────
# 4. DWARF Debug Information Extraction
# ─────────────────────────────────────────────────────────────────────────────

def extract_dwarf_loop_bounds(
    elf_path: str,
    function_name: Optional[str] = None,
    cfg: Optional[FunctionCFG] = None,
) -> Dict[str, int]:
    """
    Extracts loop bounds from DWARF debug information if available.
    Inspects:
      - DW_TAG_loop (DWARF 5 loop iteration count)
      - DW_TAG_subprogram matching function_name
      - Local DW_TAG_variable / DW_TAG_constant with DW_AT_const_value
      - Local DW_TAG_array_type / DW_TAG_subrange_type (DW_AT_upper_bound)
        for arrays iterated in the function

    Returns:
      Mapping: bb_id -> bound
    """
    if not os.path.exists(elf_path):
        return {}

    bounds: Dict[str, int] = {}
    candidate_bounds: List[int] = []

    try:
        with open(elf_path, 'rb') as f:
            elf = ELFFile(f)
            if not elf.has_dwarf_info():
                return {}

            dwarf = elf.get_dwarf_info()
            for cu in dwarf.iter_CUs():
                for die in cu.iter_DIEs():
                    if die.tag == 'DW_TAG_loop':
                        count_attr = die.attributes.get('DW_AT_count') or die.attributes.get('DW_AT_upper_bound')
                        if count_attr and isinstance(count_attr.value, int):
                            val = count_attr.value
                            if 1 <= val <= 100000:
                                candidate_bounds.append(val)

                    if die.tag == 'DW_TAG_subprogram':
                        name_attr = die.attributes.get('DW_AT_name')
                        if not name_attr:
                            continue
                        sub_name = name_attr.value.decode('utf-8', errors='ignore')
                        if function_name and sub_name != function_name:
                            continue

                        for child in die.iter_children():
                            cval_attr = child.attributes.get('DW_AT_const_value')
                            if cval_attr and isinstance(cval_attr.value, int):
                                val = cval_attr.value
                                if 1 <= val <= 100000:
                                    candidate_bounds.append(val)

                            type_attr = child.attributes.get('DW_AT_type')
                            if type_attr and isinstance(type_attr.value, int):
                                try:
                                    type_die = cu.get_DIE_from_refaddr(cu.cu_offset + type_attr.value)
                                    if type_die and type_die.tag == 'DW_TAG_array_type':
                                        for arr_child in type_die.iter_children():
                                            if arr_child.tag == 'DW_TAG_subrange_type':
                                                ub = arr_child.attributes.get('DW_AT_upper_bound')
                                                if ub and isinstance(ub.value, int):
                                                    val = ub.value + 1
                                                    if 1 <= val <= 100000:
                                                        candidate_bounds.append(val)
                                except Exception:
                                    pass

    except Exception:
        return {}

    if cfg and candidate_bounds:
        loop_headers = [bid for bid, bb in cfg.blocks.items() if bb.is_loop_header]
        if len(loop_headers) == 1 and candidate_bounds:
            bounds[loop_headers[0]] = max(candidate_bounds)
        elif len(loop_headers) > 1:
            for idx, bid in enumerate(loop_headers):
                if idx < len(candidate_bounds):
                    bounds[bid] = candidate_bounds[idx]
                else:
                    bounds[bid] = max(candidate_bounds)

    return bounds


# ─────────────────────────────────────────────────────────────────────────────
# 5. Phase 3 Coordinator: extract_loop_bounds
# ─────────────────────────────────────────────────────────────────────────────

def _find_opt_info_file(elf_path: Optional[str]) -> Optional[str]:
    """Auto-detects GCC -fopt-info log file in the directory of the ELF binary."""
    if not elf_path or not os.path.exists(elf_path):
        return None

    elf_dir = os.path.dirname(os.path.abspath(elf_path))
    patterns = [
        os.path.join(elf_dir, "*opt-info*.log"),
        os.path.join(elf_dir, "*opt-info*.txt"),
        os.path.join(elf_dir, "*opt_info*.log"),
        os.path.join(elf_dir, "*opt_info*.txt"),
        os.path.join(elf_dir, "*loop*.log"),
        os.path.join(elf_dir, "*loops*.txt"),
    ]
    for pat in patterns:
        matches = glob.glob(pat)
        if matches:
            return matches[0]
    return None


def extract_loop_bounds(
    cfg: FunctionCFG,
    elf_path: Optional[str] = None,
    user_loop_bounds: Optional[Dict] = None,
    opt_info_path: Optional[str] = None,
    max_loop_bound: int = 1000,
    strict_bounds: bool = False,
) -> LoopBoundResult:
    """
    Extracts loop bounds for all loops in cfg according to strict priority:
      1. User Annotations (highest priority)
      2. GCC -fopt-info-loop (proven SCEV compiler bounds bridged via DWARF lines)
      3. DWARF Debug Information (subprogram variables / array upper bounds)
      4. Static Constant Pattern Detection (assembly comparisons)
      5. Conservative Fallback (max_loop_bound) -> [IPET-CONSERVATIVE]

    Args:
        cfg: The function CFG from build_cfg.
        elf_path: Optional path to firmware ELF for DWARF parsing.
        user_loop_bounds: Optional user annotations from config/CLI.
        opt_info_path: Path to GCC -fopt-info-loop log file (auto-detected if None).
        max_loop_bound: Fallback bound when loop cannot be determined (default: 1000).
        strict_bounds: If True, do not apply fallback; leave loop unbounded.

    Returns:
        LoopBoundResult dataclass.
    """
    result = LoopBoundResult()
    loop_header_bids = [bid for bid, bb in cfg.blocks.items() if bb.is_loop_header]

    if not loop_header_bids:
        result.wcet_tag = "[IPET]"
        return result

    # ── Source 1: User Annotations ───────────────────────────────────────────
    user_map = normalize_user_loop_bounds(user_loop_bounds, cfg)
    for bid, bound in user_map.items():
        if bid in cfg.blocks and cfg.blocks[bid].is_loop_header:
            result.bounds[bid] = bound
            result.sources[bid] = "user_annotation"
            cfg.blocks[bid].loop_bound = bound

    # ── Source 2: GCC -fopt-info-loop (proven compiler bounds) ───────────────
    resolved_opt_info = opt_info_path or _find_opt_info_file(elf_path)
    if resolved_opt_info and elf_path:
        opt_records = parse_gcc_opt_info(resolved_opt_info)
        opt_bounds = correlate_opt_info_to_cfg(opt_records, elf_path, cfg)
        for bid, (bound, prov) in opt_bounds.items():
            if bid not in result.bounds and bid in cfg.blocks:
                result.bounds[bid] = bound
                result.sources[bid] = prov
                cfg.blocks[bid].loop_bound = bound

    # ── Source 3: DWARF Debug Info ───────────────────────────────────────────
    if elf_path:
        dwarf_map = extract_dwarf_loop_bounds(elf_path, function_name=cfg.name, cfg=cfg)
        for bid, bound in dwarf_map.items():
            if bid not in result.bounds and bid in cfg.blocks:
                result.bounds[bid] = bound
                result.sources[bid] = "dwarf_debug_info"
                cfg.blocks[bid].loop_bound = bound

    # ── Source 4: Static Constant Pattern ────────────────────────────────────
    pattern_map = detect_constant_loop_bound(cfg)
    for bid, bound in pattern_map.items():
        if bid not in result.bounds:
            result.bounds[bid] = bound
            result.sources[bid] = "constant_pattern"
            cfg.blocks[bid].loop_bound = bound

    # ── Source 5: Check Unbounded Loops and Apply Fallback ───────────────────
    unbounded: List[str] = [bid for bid in loop_header_bids if bid not in result.bounds]
    result.unbounded_loops = unbounded

    if unbounded:
        if strict_bounds:
            result.is_conservative = True
            result.wcet_tag = "[CALCULATED]"
        else:
            for bid in unbounded:
                result.bounds[bid] = max_loop_bound
                result.sources[bid] = f"conservative_fallback({max_loop_bound})"
                cfg.blocks[bid].loop_bound = max_loop_bound
            result.is_conservative = True
            result.wcet_tag = "[IPET-CONSERVATIVE]"
            if len(unbounded) >= 2 or len(loop_header_bids) >= 2:
                result.fallback_inflation_warning = True
    else:
        result.is_conservative = False
        # Distinguish user-supplied annotations from formal compiler/hardware-proven bounds
        if any(src == "user_annotation" for src in result.sources.values()):
            result.wcet_tag = "[IPET-ANNOTATED]"
        else:
            result.wcet_tag = "[IPET]"

    return result
